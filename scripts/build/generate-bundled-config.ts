// Bundled-config codegen (ADR-059).
//
// Reads the substrate's request-time static configs (YAML + markdown) from
// the repo, validates them via the same validators the runtime loaders use,
// and emits typed TypeScript modules under prototype/src/lib/atelier/__bundled__/.
//
// Why: Cloudflare Workers has no node:fs at request time. opennextjs-cloudflare
// bundles the prototype tree as a Worker; configs must travel inside that
// bundle as imports rather than runtime file reads. See ADR-059 for the
// decision + canonical-pattern citation (OpenNext on Cloudflare + Next.js
// "Importing JSON" pattern).
//
// Idempotent: re-running with no upstream changes produces byte-identical
// output. The CI codegen-drift check (.github/workflows/atelier-audit.yml
// fast-checks) runs this and fails if the working tree diff is non-empty.
//
// Sources (declared once here; add new sources by extending SOURCES):
//   - .atelier/prototype.yaml          -> prototype-manifest.bundled.ts
//   - .atelier/config.yaml            -> observability-config.bundled.ts
//                                        (extracts the `observability` block only;
//                                         find_similar config stays runtime per ADR-059
//                                         because adopters override via env vars)
//   - prototypes/<project>/docs/      -> design-principles.bundled.ts
//     design-principles.md             (path resolved via manifest's
//                                       traceability_source.design_principles)
//
// Usage:
//   npx tsx scripts/build/generate-bundled-config.ts
//   # or via npm script: npm run codegen

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const __filename = fileURLToPath(import.meta.url);
const REPO_ROOT = resolve(dirname(__filename), '..', '..');
const OUTPUT_DIR = join(REPO_ROOT, 'prototype', 'src', 'lib', 'atelier', '__bundled__');

const HEADER = `// AUTO-GENERATED by scripts/build/generate-bundled-config.ts.
// Do not edit by hand. Regenerate via \`npm run codegen\` after editing
// the source manifest / config. CI fails on drift (see ADR-059).
`;

// ---------------------------------------------------------------------------
// Shared shape definitions (mirror the runtime loaders' validators).
// Keeping them inline (not imported from prototype/src/) avoids a circular
// module dependency in tsx-only execution.
// ---------------------------------------------------------------------------

interface PrototypeSurface {
  route: string;
  strategy_notes: string;
  dps: string[];
}

type PrototypeDesignTheme = 'inherit' | 'override';

interface PrototypeDesign {
  theme: PrototypeDesignTheme;
}

interface PrototypeManifest {
  name: string;
  content_path: string;
  design?: PrototypeDesign;
  traceability_source?: {
    design_principles?: string;
    research_dir?: string;
  };
  surfaces: PrototypeSurface[];
}

interface ObservabilityThresholds {
  sessionsActivePerProject: number;
  sessionsActivePerGuild: number;
  contributionsLifetimePerProject: number;
  contributionsLifetimePerGuild: number;
  decisionsLifetimePerProject: number;
  locksHeldConcurrentPerProject: number;
  vectorIndexRowsPerGuild: number;
  triagePendingBacklog: number;
  syncLagSecondsP95: number;
  costUsdPerDayPerProject: number;
}

interface ObservabilityConfig {
  thresholds: ObservabilityThresholds;
  lookbackSeconds: number;
}

interface DpExcerpt {
  id: string;
  title: string;
  body_markdown: string;
}

type DpExcerptMap = Record<string, DpExcerpt>;

interface DesignPrinciplesBundle {
  // The source path relative to repo root (or null when the manifest does not
  // declare a design_principles path).
  sourcePath: string | null;
  excerpts: DpExcerptMap;
  // 'ok' when the file existed and was parsed; 'not_configured' when the
  // manifest had no traceability_source.design_principles; 'file_missing'
  // when declared but absent at codegen time.
  status: 'ok' | 'not_configured' | 'file_missing';
}

const DEFAULT_OBSERVABILITY_CONFIG: ObservabilityConfig = {
  thresholds: {
    sessionsActivePerProject: 20,
    sessionsActivePerGuild: 100,
    contributionsLifetimePerProject: 10000,
    contributionsLifetimePerGuild: 50000,
    decisionsLifetimePerProject: 500,
    locksHeldConcurrentPerProject: 20,
    vectorIndexRowsPerGuild: 100000,
    triagePendingBacklog: 25,
    syncLagSecondsP95: 300,
    costUsdPerDayPerProject: 10,
  },
  lookbackSeconds: 86400,
};

// ---------------------------------------------------------------------------
// Validators (mirror prototype/src/lib/atelier/prototype-manifest.ts).
// ---------------------------------------------------------------------------

function isObject(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

function validateManifest(raw: unknown): PrototypeManifest {
  if (!isObject(raw)) throw new Error('Manifest root must be an object.');
  const name = raw['name'];
  if (typeof name !== 'string' || !/^[a-z0-9][a-z0-9-]*$/.test(name)) {
    throw new Error(`manifest.name must be URL-safe slug (got: ${JSON.stringify(name)}).`);
  }
  const contentPath = raw['content_path'];
  if (typeof contentPath !== 'string' || contentPath.length === 0) {
    throw new Error('manifest.content_path must be a non-empty string.');
  }
  const surfacesRaw = raw['surfaces'];
  if (!Array.isArray(surfacesRaw) || surfacesRaw.length === 0) {
    throw new Error('manifest.surfaces must be a non-empty array.');
  }
  const surfaces: PrototypeSurface[] = surfacesRaw.map((entry, idx) => {
    if (!isObject(entry)) throw new Error(`surfaces[${idx}] must be object.`);
    const route = entry['route'];
    if (typeof route !== 'string' || !route.startsWith('/')) {
      throw new Error(`surfaces[${idx}].route must start with '/'.`);
    }
    const strategyNotes = entry['strategy_notes'];
    if (typeof strategyNotes !== 'string') {
      throw new Error(`surfaces[${idx}].strategy_notes must be a string.`);
    }
    const dpsRaw = entry['dps'];
    if (!Array.isArray(dpsRaw) || !dpsRaw.every((d) => typeof d === 'string')) {
      throw new Error(`surfaces[${idx}].dps must be string[].`);
    }
    return { route, strategy_notes: strategyNotes, dps: dpsRaw as string[] };
  });

  // ADR-060 PR E — design.theme: inherit | override (defaults to inherit
  // when block absent, so existing manifests keep validating).
  let design: PrototypeDesign | undefined;
  const designRaw = raw['design'];
  if (designRaw !== undefined && designRaw !== null) {
    if (!isObject(designRaw)) throw new Error('manifest.design must be an object if present.');
    const themeRaw = designRaw['theme'];
    if (themeRaw !== undefined && themeRaw !== 'inherit' && themeRaw !== 'override') {
      throw new Error(
        `manifest.design.theme must be 'inherit' | 'override' (got: ${JSON.stringify(themeRaw)}).`,
      );
    }
    design = { theme: (themeRaw as PrototypeDesignTheme) ?? 'inherit' };
  } else {
    design = { theme: 'inherit' };
  }

  const tsRaw = raw['traceability_source'];
  let traceability_source: PrototypeManifest['traceability_source'];
  if (tsRaw !== undefined && tsRaw !== null) {
    if (!isObject(tsRaw)) throw new Error('traceability_source must be object if present.');
    const dp = tsRaw['design_principles'];
    const research = tsRaw['research_dir'];
    if (dp !== undefined && typeof dp !== 'string') {
      throw new Error('traceability_source.design_principles must be string.');
    }
    if (research !== undefined && typeof research !== 'string') {
      throw new Error('traceability_source.research_dir must be string.');
    }
    traceability_source = {
      ...(dp ? { design_principles: dp } : {}),
      ...(research ? { research_dir: research } : {}),
    };
  }

  return {
    name,
    content_path: contentPath,
    ...(design ? { design } : {}),
    ...(traceability_source ? { traceability_source } : {}),
    surfaces,
  };
}

// Mirrors observability-config.ts (snake_case yaml -> camelCase ts).
function mergeObservabilityConfig(yamlRaw: unknown): ObservabilityConfig {
  if (!isObject(yamlRaw)) return DEFAULT_OBSERVABILITY_CONFIG;
  const block = yamlRaw['observability'];
  if (!isObject(block)) return DEFAULT_OBSERVABILITY_CONFIG;
  const t = isObject(block['thresholds']) ? block['thresholds'] : {};
  const d = DEFAULT_OBSERVABILITY_CONFIG.thresholds;
  const num = (v: unknown, fallback: number): number =>
    typeof v === 'number' && Number.isFinite(v) ? v : fallback;
  return {
    thresholds: {
      sessionsActivePerProject: num(t['sessions_active_per_project'], d.sessionsActivePerProject),
      sessionsActivePerGuild: num(t['sessions_active_per_guild'], d.sessionsActivePerGuild),
      contributionsLifetimePerProject: num(
        t['contributions_lifetime_per_project'],
        d.contributionsLifetimePerProject,
      ),
      contributionsLifetimePerGuild: num(
        t['contributions_lifetime_per_guild'],
        d.contributionsLifetimePerGuild,
      ),
      decisionsLifetimePerProject: num(
        t['decisions_lifetime_per_project'],
        d.decisionsLifetimePerProject,
      ),
      locksHeldConcurrentPerProject: num(
        t['locks_held_concurrent_per_project'],
        d.locksHeldConcurrentPerProject,
      ),
      vectorIndexRowsPerGuild: num(t['vector_index_rows_per_guild'], d.vectorIndexRowsPerGuild),
      triagePendingBacklog: num(t['triage_pending_backlog'], d.triagePendingBacklog),
      syncLagSecondsP95: num(t['sync_lag_seconds_p95'], d.syncLagSecondsP95),
      costUsdPerDayPerProject: num(
        t['cost_usd_per_day_per_project'],
        d.costUsdPerDayPerProject,
      ),
    },
    lookbackSeconds: num(block['lookback_seconds'], DEFAULT_OBSERVABILITY_CONFIG.lookbackSeconds),
  };
}

// Mirrors traceability-data.ts parseDesignPrinciples.
const DP_HEADING_RE = /^###\s+(DP-[A-Za-z0-9]+)\s*[—–-]\s*(.+?)\s*$/gm;
function parseDesignPrinciples(markdown: string): DpExcerptMap {
  const out: DpExcerptMap = {};
  const matches: Array<{ id: string; title: string; bodyStart: number }> = [];
  for (const m of markdown.matchAll(DP_HEADING_RE)) {
    const id = m[1];
    const title = m[2];
    if (!id || title === undefined) continue;
    const idx = m.index ?? 0;
    const headingEnd = idx + m[0].length;
    matches.push({ id, title: title.trim(), bodyStart: headingEnd });
  }
  for (let i = 0; i < matches.length; i++) {
    const cur = matches[i]!;
    const next = matches[i + 1];
    let sliceEnd = next ? next.bodyStart : markdown.length;
    if (next) {
      sliceEnd = markdown.lastIndexOf('\n###', sliceEnd);
      if (sliceEnd < cur.bodyStart) sliceEnd = next.bodyStart;
    }
    const body = markdown.slice(cur.bodyStart, sliceEnd).replace(/^\n+/, '').replace(/\s+$/, '');
    out[cur.id] = { id: cur.id, title: cur.title, body_markdown: body };
  }
  return out;
}

// ---------------------------------------------------------------------------
// Emit helpers — deterministic JSON.stringify with stable key order.
// ---------------------------------------------------------------------------

function stableStringify(value: unknown, indent = 2): string {
  return JSON.stringify(value, replacer, indent);
  function replacer(_key: string, v: unknown): unknown {
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      const out: Record<string, unknown> = {};
      for (const k of Object.keys(v as Record<string, unknown>).sort()) {
        out[k] = (v as Record<string, unknown>)[k];
      }
      return out;
    }
    return v;
  }
}

function emitModule(filename: string, exportName: string, typeName: string, value: unknown): void {
  const body = `${HEADER}
// Source-of-truth: see scripts/build/generate-bundled-config.ts for the
// emit pipeline. Edit the upstream config file, not this module.

export const ${exportName} = ${stableStringify(value)} as const;

export type ${typeName} = typeof ${exportName};
`;
  const outPath = join(OUTPUT_DIR, filename);
  if (!existsSync(OUTPUT_DIR)) mkdirSync(OUTPUT_DIR, { recursive: true });
  writeFileSync(outPath, body);
  process.stdout.write(`  wrote ${outPath.replace(REPO_ROOT + '/', '')}\n`);
}

// ---------------------------------------------------------------------------
// Pipeline.
// ---------------------------------------------------------------------------

function main(): void {
  process.stdout.write('generate-bundled-config: starting\n');

  // 1. prototype.yaml
  const manifestPath = join(REPO_ROOT, '.atelier', 'prototype.yaml');
  if (!existsSync(manifestPath)) {
    throw new Error(`Source missing: ${manifestPath}. Create .atelier/prototype.yaml per ADR-057.`);
  }
  const manifestRaw = readFileSync(manifestPath, 'utf8');
  const manifest = validateManifest(parseYaml(manifestRaw));
  emitModule(
    'prototype-manifest.bundled.ts',
    'BUNDLED_PROTOTYPE_MANIFEST',
    'BundledPrototypeManifest',
    manifest,
  );

  // 2. observability config (subset of .atelier/config.yaml).
  // Defaults survive if the file or block is missing.
  const configPath = join(REPO_ROOT, '.atelier', 'config.yaml');
  let observability: ObservabilityConfig = DEFAULT_OBSERVABILITY_CONFIG;
  if (existsSync(configPath)) {
    observability = mergeObservabilityConfig(parseYaml(readFileSync(configPath, 'utf8')));
  }
  emitModule(
    'observability-config.bundled.ts',
    'BUNDLED_OBSERVABILITY_CONFIG',
    'BundledObservabilityConfig',
    observability,
  );

  // 3. design-principles excerpts (path declared by the manifest).
  const dpDeclared = manifest.traceability_source?.design_principles;
  let dpBundle: DesignPrinciplesBundle;
  if (!dpDeclared) {
    dpBundle = { sourcePath: null, excerpts: {}, status: 'not_configured' };
  } else {
    const dpAbsolute = join(REPO_ROOT, dpDeclared);
    if (!existsSync(dpAbsolute)) {
      dpBundle = { sourcePath: dpDeclared, excerpts: {}, status: 'file_missing' };
    } else {
      dpBundle = {
        sourcePath: dpDeclared,
        excerpts: parseDesignPrinciples(readFileSync(dpAbsolute, 'utf8')),
        status: 'ok',
      };
    }
  }
  emitModule(
    'design-principles.bundled.ts',
    'BUNDLED_DESIGN_PRINCIPLES',
    'BundledDesignPrinciples',
    dpBundle,
  );

  process.stdout.write('generate-bundled-config: done\n');
}

main();
